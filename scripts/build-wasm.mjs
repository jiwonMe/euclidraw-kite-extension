import { createHash } from 'node:crypto';
import { execFileSync } from 'node:child_process';
import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { homedir } from 'node:os';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

/**
 * Compiles crate-kite-solver to wasm32 (+simd128) and writes the bytes as a
 * base64 TypeScript module so the extension ships as one self-contained ESM
 * file (Blob URL installs cannot fetch side files).
 *
 * The generated module is committed. A source hash makes rebuilds incremental
 * and lets CI without a Rust toolchain verify that it is up to date.
 */
export const root = fileURLToPath(new URL('../', import.meta.url));
const crate = join(root, 'crate-kite-solver');
const generated = join(root, 'src', 'generated', 'kite-solver-wasm.ts');

function sources() {
  const files = ['Cargo.toml', '.cargo/config.toml', '../rust-toolchain.toml'];
  const walk = dir => {
    for (const entry of readdirSync(join(crate, dir), { withFileTypes: true })) {
      const path = join(dir, entry.name);
      if (entry.isDirectory()) walk(path); else files.push(path);
    }
  };
  walk('src');
  return files.sort();
}

export function sourceHash() {
  const hash = createHash('sha256');
  for (const file of sources()) {
    hash.update(file);
    const path = join(crate, file);
    if (existsSync(path)) hash.update(readFileSync(path));
  }
  return hash.digest('hex');
}

function generatedHash() {
  if (!existsSync(generated)) return undefined;
  return /KITE_SOLVER_SOURCE_HASH = '([a-f0-9]{64})'/.exec(readFileSync(generated, 'utf8'))?.[1];
}

/** A Rust toolchain from the environment, $KITE_RUST_TOOLCHAIN, or a sibling alid checkout. */
function cargoEnv() {
  const candidates = [
    process.env.KITE_RUST_TOOLCHAIN,
    process.env.ALID && join(process.env.ALID, '.toolchain'),
    join(homedir(), 'Workspace', 'alid', '.toolchain'),
  ].filter(Boolean);
  for (const toolchain of candidates) {
    const cargo = join(toolchain, 'cargo', 'bin', process.platform === 'win32' ? 'cargo.exe' : 'cargo');
    if (existsSync(cargo)) return { cargo, env: { ...process.env, CARGO_HOME: join(toolchain, 'cargo'), RUSTUP_HOME: join(toolchain, 'rustup'), PATH: `${dirname(cargo)}:${process.env.PATH}` } };
  }
  try { execFileSync('cargo', ['--version'], { stdio: 'ignore' }); return { cargo: 'cargo', env: process.env }; } catch { return undefined; }
}

export function buildWasm({ force = false, test = false } = {}) {
  const expected = sourceHash();
  const toolchain = cargoEnv();
  if (test) {
    if (!toolchain) throw new Error('cargo test requires a Rust toolchain (set KITE_RUST_TOOLCHAIN).');
    execFileSync(toolchain.cargo, ['test', '--release', '--quiet'], { cwd: crate, env: toolchain.env, stdio: 'inherit' });
  }
  if (!force && generatedHash() === expected) return { rebuilt: false, hash: expected };
  if (!toolchain) {
    if (generatedHash()) throw new Error('crate-kite-solver changed but no Rust toolchain was found. Install Rust with the wasm32-unknown-unknown target or set KITE_RUST_TOOLCHAIN.');
    throw new Error('src/generated/kite-solver-wasm.ts is missing and no Rust toolchain was found.');
  }
  execFileSync(toolchain.cargo, ['build', '--release', '--locked', '--target', 'wasm32-unknown-unknown'], { cwd: crate, env: toolchain.env, stdio: 'inherit' });
  const wasm = readFileSync(join(crate, 'target', 'wasm32-unknown-unknown', 'release', 'kite_solver.wasm'));
  if (!WebAssembly.validate(wasm, { builtins: [] }) && !WebAssembly.validate(wasm)) throw new Error('The compiled solver is not valid WebAssembly.');
  const base64 = wasm.toString('base64');
  mkdirSync(dirname(generated), { recursive: true });
  const lines = base64.match(/.{1,120}/g) ?? [];
  writeFileSync(generated, [
    '// Generated by scripts/build-wasm.mjs from crate-kite-solver. Do not edit.',
    `export const KITE_SOLVER_SOURCE_HASH = '${expected}';`,
    `export const KITE_SOLVER_WASM_BYTES = ${wasm.length};`,
    `export const KITE_SOLVER_WASM_SHA256 = '${createHash('sha256').update(wasm).digest('hex')}';`,
    'export const KITE_SOLVER_WASM_BASE64 =',
    lines.map(line => `  '${line}'`).join(' +\n') + ';',
    '',
  ].join('\n'));
  console.log(`[wasm] ${relative(root, generated)} · ${wasm.length} bytes`);
  return { rebuilt: true, hash: expected };
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) {
  const args = process.argv.slice(2);
  const result = buildWasm({ force: args.includes('--force'), test: args.includes('--test') });
  if (!result.rebuilt) console.log('[wasm] solver is up to date.');
}
