/**
 * Bundle the Penrose worker into a single ES module and commit it as a string.
 * The extension ships one file (`dist/plugin.js`), so the worker cannot be a
 * separate asset: it is embedded and started through a Blob URL.
 */
import { build } from 'vite';
import { createHash } from 'node:crypto';
import { readFile, writeFile, readdir, rm, mkdir } from 'node:fs/promises';
import { gzipSync } from 'node:zlib';

const root = new URL('../', import.meta.url);
const entry = new URL('src/penrose/engine/worker-entry.ts', root).pathname;
const outDir = new URL('.worker-build/', root).pathname;
const generated = new URL('src/generated/penrose-worker.ts', root).pathname;

/** Install budget is 5 MiB for the whole bundle; leave room for the renderer. */
const MAX_WORKER_BYTES = 4.4 * 1024 * 1024;

await rm(outDir, { recursive: true, force: true });
await mkdir(outDir, { recursive: true });

await build({
  configFile: false,
  root: root.pathname,
  logLevel: 'warn',
  define: { 'process.env.NODE_ENV': '"production"' },
  build: {
    outDir,
    emptyOutDir: true,
    minify: 'oxc',
    target: 'es2022',
    lib: { entry, formats: ['es'], fileName: () => 'worker.js' },
    rollupOptions: { external: [] },
  },
});

const files = (await readdir(outDir)).filter(file => file.endsWith('.js'));
if (files.length !== 1) throw new Error(`Worker must bundle to one file, got ${files.join(', ')}`);
const source = await readFile(`${outDir}/${files[0]}`, 'utf8');
if (/(^|\n)\s*import\s*[({"'*]/.test(source) || /import\s*\(\s*["']/.test(source)) {
  throw new Error('Worker bundle still contains an import; it cannot run as a self-contained Blob module.');
}
if (source.length > MAX_WORKER_BYTES) {
  throw new Error(`Worker bundle is ${(source.length / 1024 / 1024).toFixed(2)} MiB, over the ${(MAX_WORKER_BYTES / 1024 / 1024).toFixed(2)} MiB budget.`);
}

const sha256 = createHash('sha256').update(source).digest('hex');
const text = `// Generated by scripts/build-worker.mjs. Do not edit.
export const PENROSE_WORKER_SHA256 = '${sha256}';
export const PENROSE_WORKER_SOURCE = ${JSON.stringify(source)};
`;
await writeFile(generated, text);

console.log(
  `penrose worker: ${(source.length / 1024 / 1024).toFixed(2)} MiB ` +
  `(gzip ${(gzipSync(source).length / 1024 / 1024).toFixed(2)} MiB), ` +
  `embedded ${(text.length / 1024 / 1024).toFixed(2)} MiB, sha256 ${sha256.slice(0, 12)}…`,
);
